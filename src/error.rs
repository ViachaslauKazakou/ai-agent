//! Ошибки доменного слоя приложения.

use thiserror::Error;

/// Ошибки, которые могут возникнуть в библиотечном и консольном слоях.
#[derive(Debug, Error, PartialEq, Eq)]
pub enum AppError {
    /// Входная строка не содержит ни одного слова.
    #[error("Ввод пустой: нужно указать хотя бы одно слово.")]
    EmptyInput,

    /// Сообщение нельзя добавить в сессию без содержимого.
    #[error("Сообщение не может быть пустым.")]
    EmptyMessage,

    /// Модель необходима для идентификации конфигурации сессии.
    #[error("Имя модели не может быть пустым.")]
    EmptyModel,

    /// Значение конфигурации не прошло проверку.
    #[error("Некорректная конфигурация: {0}")]
    InvalidConfig(String),

    /// Переменная окружения содержит значение неверного типа.
    #[error("Некорректное значение переменной {name}: {value}")]
    InvalidEnvironmentValue { name: String, value: String },

    /// Не удалось прочитать `.env`.
    #[error("Не удалось загрузить файл окружения: {0}")]
    EnvironmentFile(String),

    /// Рабочая директория не существует или недоступна.
    #[error("Рабочая директория недоступна: {0}")]
    InvalidWorkingDirectory(String),

    /// LLM provider не смог обработать запрос.
    #[error("Ошибка LLM-провайдера: {0}")]
    LlmProvider(String),

    /// Ошибка сетевого запроса к LLM.
    #[error("Сетевая ошибка LLM-провайдера: {0}")]
    LlmNetwork(String),

    /// LLM вернула HTTP status вне диапазона успешных ответов.
    #[error("LLM-провайдер вернул HTTP {status}: {message}")]
    LlmHttp { status: u16, message: String },

    /// Ответ LLM не удалось разобрать как ожидаемый JSON.
    #[error("Некорректный JSON-ответ LLM: {0}")]
    LlmJson(String),

    /// JSON-ответ LLM не содержит обязательных полей.
    #[error("Некорректная структура ответа LLM: {0}")]
    LlmResponse(String),

    /// Ошибка выполнения инструмента.
    #[error("Ошибка инструмента: {0}")]
    Tool(String),

    /// Запрошенный моделью инструмент не зарегистрирован.
    #[error("Неизвестный инструмент: {0}")]
    UnknownTool(String),

    /// Инструмент попытался выйти за пределы рабочей директории.
    #[error("Путь инструмента вне рабочей директории: {0}")]
    PathOutsideWorkingDirectory(String),

    /// Изменяющий файл инструмент требует явного разрешения.
    #[error("Запись файлов запрещена: запустите агент с --allow-write")]
    WriteConfirmationRequired,

    /// Agent loop достиг заданного лимита раундов.
    #[error("Достигнут лимит раундов инструментов: {0}")]
    ToolRoundLimit(usize),

    /// Конфигурационный файл агента не удалось прочитать или разобрать.
    #[error("Ошибка конфигурационного файла: {0}")]
    AgentConfig(String),

    #[error("Ошибка сохранения сессии: {0}")]
    SessionPersistence(String),
}
