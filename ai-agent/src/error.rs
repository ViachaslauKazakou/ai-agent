//! Ошибки доменного слоя приложения.

use thiserror::Error;

/// Ошибки, которые могут возникнуть при создании и изменении доменных типов.
#[derive(Debug, Error, PartialEq, Eq)]
pub enum AppError {
    /// Входная строка не содержит ни одного слова.
    #[error("Ввод пустой: нужно указать хотя бы одно слово.")]
    EmptyInput,

    /// Сообщение нельзя добавить в сессию без содержимого.
    #[error("Сообщение не может быть пустым.")]
    EmptyMessage,

    /// Модель необходима для идентификации конфигурации сессии.
    #[error("Имя модели не может быть пустым.")]
    EmptyModel,
}
